import logging
from typing import Any, Dict, List, Optional
import httpx
from app.core.config import settings
from app.services.ai.base import BaseAIProvider
from app.services.ai.safety import AISafetyLayer

logger = logging.getLogger(__name__)

class GeminiProvider(BaseAIProvider):
    def __init__(self):
        self.api_key = settings.GEMINI_API_KEY
        self.model = settings.GEMINI_MODEL or "gemini-1.5-flash"
        self.endpoint = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model}:generateContent"

    def name(self) -> str:
        return "gemini"

    def is_configured(self) -> bool:
        return bool(self.api_key and len(self.api_key.strip()) > 5)

    async def generate_response(
        self,
        messages: List[Dict[str, str]],
        retrieved_context: Optional[List[Dict[str, Any]]] = None,
        report_data: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        if not self.is_configured():
            raise ValueError("Gemini API key is not configured in environment variables.")

        user_msg = messages[-1]["content"] if messages else ""
        is_emergency, emergency_msg, injection_alert = AISafetyLayer.inspect_query(user_msg)
        safety_alerts = []
        if injection_alert:
            safety_alerts.append(injection_alert)
        if is_emergency:
            safety_alerts.append("CRITICAL: Emergency symptoms reported.")
            return {
                "content": AISafetyLayer.append_disclaimer(emergency_msg),
                "sources": [],
                "safety_alerts": safety_alerts,
                "provider": "gemini",
                "model": self.model,
            }

        # Format system prompt and evidence grounding
        system_instruction = (
            "You are MediPredict AI, a clinical informatics and medical intelligence assistant. "
            "You provide objective, evidence-grounded scientific explanations. "
            "Never assert personal diagnoses or prescribe medications. "
            "Always cite medical references when discussing clinical findings."
        )

        context_str = ""
        sources = []
        if retrieved_context:
            context_str = "\nRetrieved Medical Evidence Grounding:\n" + "\n".join(
                [f"- {c.get('title')} ({c.get('journal', 'Medical Ref')}, {c.get('year', '2024')})" for c in retrieved_context]
            )
            sources = retrieved_context

        gemini_contents = []
        # Add prior messages
        for m in messages[:-1]:
            role = "user" if m.get("role") == "user" else "model"
            gemini_contents.append({"role": role, "parts": [{"text": m.get("content", "")}]})

        current_prompt = f"{user_msg}\n{context_str}"
        gemini_contents.append({"role": "user", "parts": [{"text": current_prompt}]})

        payload = {
            "contents": gemini_contents,
            "systemInstruction": {"parts": [{"text": system_instruction}]},
            "generationConfig": {
                "temperature": 0.2,
                "maxOutputTokens": 1024,
            },
        }

        async with httpx.AsyncClient(timeout=30.0) as client:
            resp = await client.post(
                f"{self.endpoint}?key={self.api_key}",
                json=payload,
                headers={"Content-Type": "application/json"},
            )
            resp.raise_for_status()
            data = resp.json()
            raw_text = (
                data.get("candidates", [{}])[0]
                .get("content", {})
                .get("parts", [{}])[0]
                .get("text", "No response generated by model.")
            )

        return {
            "content": AISafetyLayer.append_disclaimer(raw_text),
            "sources": sources,
            "safety_alerts": safety_alerts,
            "provider": "gemini",
            "model": self.model,
        }

    async def interpret_report(
        self,
        report_title: str,
        measurements: List[Dict[str, Any]],
    ) -> Dict[str, Any]:
        prompt = (
            f"Analyze this medical laboratory report titled '{report_title}'.\n"
            f"Measurements: {measurements}\n"
            "Provide: 1) Brief summary, 2) Clinical interpretation, 3) Key findings list, 4) Potential abnormal flags list."
        )
        resp = await self.generate_response([{"role": "user", "content": prompt}])
        return {
            "summary": f"Gemini Analysis of {report_title}",
            "interpretation": resp["content"],
            "key_findings": [f"{m.get('test_name')}: {m.get('value')} {m.get('unit')}" for m in measurements],
            "abnormalities": [f"{m.get('test_name')} is flagged {m.get('flag')}" for m in measurements if m.get("is_abnormal")],
        }
